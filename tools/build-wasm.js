// Builds the WebAssembly engine (engine-wasm/, Rust) and writes it into the plugin as base64:
// disintegration-studio/js/engine-wasm-bin.js. That file is committed, so building the plugin
// does not need Rust; run this after changing engine-wasm/src/lib.rs.
//   node tools/build-wasm.js           build and write
//   node tools/build-wasm.js --check   fail if the committed file is not what the source builds
// Needs cargo with the wasm32-unknown-unknown target (rustup target add wasm32-unknown-unknown).
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const root = path.join(__dirname, '..'), crate = path.join(root, 'engine-wasm');
const wasm = path.join(crate, 'target', 'wasm32-unknown-unknown', 'release', 'disintegration_engine.wasm');
const out = path.join(root, 'disintegration-studio', 'js', 'engine-wasm-bin.js');

execFileSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown'], { cwd: crate, stdio: 'inherit' });
const bytes = fs.readFileSync(wasm);
const b64 = bytes.toString('base64');
const lines = [];
for (let i = 0; i < b64.length; i += 120) lines.push("  '" + b64.slice(i, i + 120) + "'");
const text = [
  '/* Disintegration Studio — the WebAssembly engine (engine-wasm/), as base64. Generated by',
  ' * tools/build-wasm.js from engine-wasm/src/lib.rs: do not edit. ' + bytes.length + ' bytes. */',
  '(function (root) {',
  "  root.DISINTEGRATION_WASM = (",
  lines.join(' +\n'),
  '  );',
  "})(typeof window !== 'undefined' ? window : globalThis);",
  '',
].join('\n');
if (process.argv.includes('--check')) {
  const old = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (old !== text) { console.error('engine-wasm-bin.js is out of date: run node tools/build-wasm.js'); process.exit(1); }
  console.log('engine-wasm-bin.js is up to date (' + bytes.length + ' bytes)');
} else {
  fs.writeFileSync(out, text);
  console.log('wrote ' + path.relative(root, out) + ': ' + bytes.length + ' bytes of WebAssembly, ' + text.length + ' characters');
}
